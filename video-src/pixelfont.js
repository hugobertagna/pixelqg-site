/*
 * PixelQG pixel font — 5x7 capitals, shared by the video renderer (canvas)
 * and tools/build-font.js (which turns it into fonts/pixelqg-pixel.ttf for the site).
 * Rows are drawn from the cap top (row 0) to the baseline (row 6).
 * `y` shifts a glyph: -2 = accents above the cap, 7-8 = descenders.
 */
(function (root) {
  const G = {};
  const def = (ch, rows, y = 0) => { G[ch] = { y, r: rows }; };

  def('A', ['.###.', '#...#', '#...#', '#####', '#...#', '#...#', '#...#']);
  def('B', ['####.', '#...#', '#...#', '####.', '#...#', '#...#', '####.']);
  def('C', ['.###.', '#...#', '#....', '#....', '#....', '#...#', '.###.']);
  def('D', ['####.', '#...#', '#...#', '#...#', '#...#', '#...#', '####.']);
  def('E', ['#####', '#....', '#....', '####.', '#....', '#....', '#####']);
  def('F', ['#####', '#....', '#....', '####.', '#....', '#....', '#....']);
  def('G', ['.###.', '#...#', '#....', '#.###', '#...#', '#...#', '.####']);
  def('H', ['#...#', '#...#', '#...#', '#####', '#...#', '#...#', '#...#']);
  def('I', ['###', '.#.', '.#.', '.#.', '.#.', '.#.', '###']);
  def('J', ['..###', '...#.', '...#.', '...#.', '#..#.', '#..#.', '.##..']);
  def('K', ['#...#', '#..#.', '#.#..', '##...', '#.#..', '#..#.', '#...#']);
  def('L', ['#....', '#....', '#....', '#....', '#....', '#....', '#####']);
  def('M', ['#...#', '##.##', '#.#.#', '#.#.#', '#...#', '#...#', '#...#']);
  def('N', ['#...#', '#...#', '##..#', '#.#.#', '#..##', '#...#', '#...#']);
  def('O', ['.###.', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.']);
  def('P', ['####.', '#...#', '#...#', '####.', '#....', '#....', '#....']);
  def('Q', ['.###.', '#...#', '#...#', '#...#', '#.#.#', '#..#.', '.##.#']);
  def('R', ['####.', '#...#', '#...#', '####.', '#.#..', '#..#.', '#...#']);
  def('S', ['.####', '#....', '#....', '.###.', '....#', '....#', '####.']);
  def('T', ['#####', '..#..', '..#..', '..#..', '..#..', '..#..', '..#..']);
  def('U', ['#...#', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.']);
  def('V', ['#...#', '#...#', '#...#', '#...#', '#...#', '.#.#.', '..#..']);
  def('W', ['#...#', '#...#', '#...#', '#.#.#', '#.#.#', '#.#.#', '.#.#.']);
  def('X', ['#...#', '#...#', '.#.#.', '..#..', '.#.#.', '#...#', '#...#']);
  def('Y', ['#...#', '#...#', '.#.#.', '..#..', '..#..', '..#..', '..#..']);
  def('Z', ['#####', '....#', '...#.', '..#..', '.#...', '#....', '#####']);
  def('Œ', ['.######', '#..#...', '#..#...', '#..####', '#..#...', '#..#...', '.######']);

  def('0', ['.###.', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.']);
  def('1', ['.#.', '##.', '.#.', '.#.', '.#.', '.#.', '###']);
  def('2', ['.###.', '#...#', '....#', '...#.', '..#..', '.#...', '#####']);
  def('3', ['####.', '....#', '....#', '.###.', '....#', '....#', '####.']);
  def('4', ['...#.', '..##.', '.#.#.', '#..#.', '#####', '...#.', '...#.']);
  def('5', ['#####', '#....', '####.', '....#', '....#', '#...#', '.###.']);
  def('6', ['.###.', '#....', '#....', '####.', '#...#', '#...#', '.###.']);
  def('7', ['#####', '....#', '...#.', '..#..', '..#..', '..#..', '..#..']);
  def('8', ['.###.', '#...#', '#...#', '.###.', '#...#', '#...#', '.###.']);
  def('9', ['.###.', '#...#', '#...#', '.####', '....#', '....#', '.###.']);

  def(' ', ['...']);
  def('.', ['#'], 6);
  def(',', ['.#', '.#', '#.'], 5);
  def(':', ['#', '.', '.', '#'], 2);
  def(';', ['.#', '..', '..', '.#', '.#', '#.'], 2);
  def('!', ['#', '#', '#', '#', '#', '.', '#']);
  def('?', ['.###.', '#...#', '....#', '...#.', '..#..', '.....', '..#..']);
  def("'", ['#', '#']);
  def('’', ['.#', '.#', '#.']);
  def('"', ['#.#', '#.#']);
  def('-', ['###'], 3);
  def('–', ['#####'], 3);
  def('—', ['#######'], 3);
  def('_', ['#####'], 6);
  def('/', ['....#', '...#.', '...#.', '..#..', '.#...', '.#...', '#....']);
  def('(', ['..#', '.#.', '#..', '#..', '#..', '.#.', '..#']);
  def(')', ['#..', '.#.', '..#', '..#', '..#', '.#.', '#..']);
  def('[', ['##', '#.', '#.', '#.', '#.', '#.', '##']);
  def(']', ['##', '.#', '.#', '.#', '.#', '.#', '##']);
  def('+', ['..#..', '..#..', '#####', '..#..', '..#..'], 1);
  def('=', ['#####', '.....', '#####'], 2);
  def('*', ['#.#.#', '.###.', '#####', '.###.', '#.#.#'], 1);
  def('%', ['##..#', '##..#', '...#.', '..#..', '.#...', '#..##', '#..##']);
  def('&', ['.##..', '#..#.', '#.#..', '.#...', '#.#.#', '#..#.', '.##.#']);
  def('@', ['.###.', '#...#', '#.###', '#.#.#', '#.###', '#....', '.####']);
  def('#', ['.#.#.', '.#.#.', '#####', '.#.#.', '#####', '.#.#.', '.#.#.']);
  def('<', ['...#', '..#.', '.#..', '#...', '.#..', '..#.', '...#']);
  def('>', ['#...', '.#..', '..#.', '...#', '..#.', '.#..', '#...']);
  def('«', ['..#.#', '.#.#.', '#.#..', '.#.#.', '..#.#'], 1);
  def('»', ['#.#..', '.#.#.', '..#.#', '.#.#.', '#.#..'], 1);
  def('€', ['..###', '.#...', '####.', '.#...', '####.', '.#...', '..###']);
  def('$', ['..#..', '.####', '#.#..', '.###.', '..#.#', '####.', '..#..']);
  def('…', ['#.#.#'], 6);
  def('·', ['#'], 3);
  def('•', ['##', '##'], 2);
  def('|', ['#', '#', '#', '#', '#', '#', '#']);
  def('×', ['#...#', '.#.#.', '..#..', '.#.#.', '#...#'], 1);
  def('✓', ['......#', '.....#.', '#...#..', '.#.#...', '..#....'], 1);
  def('→', ['...#..', '....#.', '######', '....#.', '...#..'], 1);
  def('°', ['.#.', '#.#', '.#.'], 0);

  // Accented capitals are composed from a base glyph and an accent above.
  const ACC = {
    acute: ['...#.', '..#..'], grave: ['.#...', '..#..'], circ: ['..#..', '.#.#.'], uml: ['.#.#.', '.....'],
  };
  const ACC3 = { circ: ['.#.', '#.#'], uml: ['#.#', '...'] };
  const accent = (ch, base, kind) => {
    const b = G[base];
    const a = (b.r[0].length === 3 ? ACC3 : ACC)[kind];
    def(ch, a.concat(b.r), -2);
  };
  accent('É', 'E', 'acute'); accent('È', 'E', 'grave'); accent('Ê', 'E', 'circ'); accent('Ë', 'E', 'uml');
  accent('À', 'A', 'grave'); accent('Â', 'A', 'circ'); accent('Ä', 'A', 'uml');
  accent('Î', 'I', 'circ'); accent('Ï', 'I', 'uml');
  accent('Ô', 'O', 'circ'); accent('Ö', 'O', 'uml');
  accent('Ù', 'U', 'grave'); accent('Û', 'U', 'circ'); accent('Ü', 'U', 'uml');
  def('Ç', G.C.r.concat(['..#..', '.##..']));

  // Lowercase (and a few look-alikes) map onto the capitals: the font is caps-only.
  const ALIAS = { " ": ' ', ' ': ' ', '’': '’', '‘': "'" };
  for (const ch of Object.keys(G)) {
    const lo = ch.toLowerCase();
    if (lo !== ch && !G[lo]) ALIAS[lo] = ch;
  }

  const lookup = (ch) => G[ch] || G[ALIAS[ch]] || null;
  const width = (g) => g.r.reduce((m, row) => Math.max(m, row.length), 0);
  const advance = (g) => width(g) + 1;

  function measure(text) {
    let w = 0;
    for (const ch of text) { const g = lookup(ch); w += g ? advance(g) : 4; }
    return Math.max(0, w - 1);
  }

  // Draws text with its cap top at (x, y); `s` is the size of one font pixel.
  function draw(ctx, text, x, y, s, color, opts = {}) {
    const align = opts.align || 'left';
    const w = measure(text) * s;
    let cx = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
    cx = Math.round(cx); y = Math.round(y);
    const visible = opts.chars == null ? Infinity : opts.chars;
    let n = 0;
    ctx.fillStyle = color;
    for (const ch of text) {
      const g = lookup(ch);
      if (!g) { cx += 4 * s; continue; }
      if (n++ >= visible) break;
      g.r.forEach((row, ry) => {
        let run = -1;
        for (let rx = 0; rx <= row.length; rx++) {
          const on = row[rx] === '#';
          if (on && run < 0) run = rx;
          if (!on && run >= 0) { ctx.fillRect(cx + run * s, y + (g.y + ry) * s, (rx - run) * s, s); run = -1; }
        }
      });
      cx += advance(g) * s;
    }
    return w;
  }

  const api = { glyphs: G, alias: ALIAS, lookup, width, advance, measure, draw, capHeight: 7 };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.PixelFont = api;
})(typeof window !== 'undefined' ? window : globalThis);
